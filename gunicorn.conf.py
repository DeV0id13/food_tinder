import os
from pathlib import Path

from gunicorn.workers.gthread import ThreadWorker
from prometheus_client import multiprocess


def positive_int(name: str, default: int) -> int:
    try:
        value = int(os.environ.get(name, str(default)))
    except ValueError as exc:
        raise ValueError(f"{name} must be a positive integer") from exc
    if value < 1:
        raise ValueError(f"{name} must be a positive integer")
    return value


workers = positive_int("GUNICORN_WORKERS", 2)
threads = positive_int("GUNICORN_THREADS", 2)
worker_class = "gthread"


def on_starting(server) -> None:
    # Gunicorn has resolved environment and CLI overrides by this point.
    cfg = server.cfg
    if cfg.workers < 1 or cfg.threads < 1:
        raise ValueError("Gunicorn workers and threads must be positive")
    if cfg.threads > 1 and not issubclass(server.worker_class, ThreadWorker):
        raise ValueError("Multiple threads require the gthread worker class")
    if directory := os.environ.get("PROMETHEUS_MULTIPROC_DIR"):
        for path in Path(directory).glob("*.db"):
            path.unlink()
    server.log.info(
        "Gunicorn configuration: workers=%s threads=%s worker_class=%s",
        cfg.workers,
        cfg.threads,
        cfg.worker_class_str,
    )


def child_exit(server, worker) -> None:
    if os.environ.get("PROMETHEUS_MULTIPROC_DIR"):
        multiprocess.mark_process_dead(worker.pid)


