function recipe({id, title, image = '', minutes, difficulty = 2, meals, description, lines, steps}) {
  return {
    id,
    title,
    image_url: image ? `/assets/${image}.jpg` : '',
    cooking_time_minutes: minutes,
    difficulty,
    base_servings: 2,
    meal_types: meals,
    // Unknown nutrition and price stay null instead of pretending to be calculated.
    kcal_per_serving: null,
    protein_g_per_serving: null,
    fat_g_per_serving: null,
    carbs_g_per_serving: null,
    estimated_price_rub_per_serving: null,
    description,
    steps,
    ingredients: lines.map(([key, quantity]) => {
      const [ingredient_id, name, unit] = ingredients[key];
      return {ingredient_id, name, unit, quantity: quantity.toFixed(3)};
    }),
  };
}

