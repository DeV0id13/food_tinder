import {normalizeSearch} from './search.js';

const GROUPS = [
  ['Овощи и фрукты', [
    /(?:^| )(?:томат|помидор|картоф|морков|огур|капуст|лук|чеснок|свекл|брокколи|шпинат|кабач|баклажан)/,
    /(?:^| )(?:яблок|банан|ягод|лимон|авокадо|апельсин|груш|клубник|черник)/,
    /(?:^| )(?:зелень|укроп|петрушк|гриб|шампиньон|салат лист|редис|тыкв|перец болгар|болгарск\p{L}* перец)/u,
  ]],
  ['Мясо и рыба', [
    /(?:^| )(?:курин|куриц|говядин|свинин|индейк|фарш|бекон|ветчин)/,
    /(?:^| )(?:рыб|лосос|форел|тунец|тунц|треск|кревет|минтай|скумбр)/,
  ]],
  ['Молочные продукты и яйца', [
    /(?:^| )(?:молок|сливки|йогурт|творог|сметан|сыр|кефир|яйц|масло сливоч|сливочн\p{L}* масло)/u,
  ]],
  ['Бакалея', [
    /(?:^| )(?:рис|овсян|круп|греч|булгур|кускус|макарон|паст[аы]|мук|хлеб)/,
    /(?:^| )(?:сахар|соль|масло|мед|орех|чечевиц|нут|фасол|специ|перец|соус|уксус|крахмал|изюм|кунжут|кориц)/,
  ]],
];

export function groupShoppingItems(items) {
  const buckets = new Map([...GROUPS.map(([label]) => [label, []]), ['Прочее', []]]);
  for (const item of items) {
    const name = normalizeSearch(item.name).replace(/[^\p{L}]+/gu, ' ');
    const group = GROUPS.find(([, patterns]) => patterns.some((pattern) => pattern.test(name)));
    buckets.get(group?.[0] ?? 'Прочее').push(item);
  }
  return [...buckets].filter(([, entries]) => entries.length);
}
