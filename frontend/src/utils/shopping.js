import {normalizeSearch} from './search.js';

const GROUPS = [
  ['Овощи и фрукты', /томат|помидор|картоф|морков|огур|капуст|лук|чеснок|перец болгар|болгарск.*перец|свекл|брокколи|шпинат|кабач|баклажан|яблок|банан|ягод|лимон|авокадо|зелень|укроп|петрушк|гриб|шампиньон|салат лист|редис|тыкв|апельсин|груш|клубник|черник/],
  ['Мясо и рыба', /курин|куриц|говядин|свинин|индейк|фарш|бекон|рыб|лосос|форел|тунец|тунц|треск|кревет|ветчин|минтай|скумбр/],
  ['Молочные продукты и яйца', /молок|сливки|йогурт|творог|сметан|сыр|кефир|яйц|масло сливоч|сливочн.*масло/],
  ['Бакалея', /рис|овсян|круп|греч|булгур|кускус|макарон|паст[аы]|мук|сахар|соль|масло|мед|орех|чечевиц|нут|фасол|хлеб|специ|перец|соус|уксус|крахмал|изюм|кунжут/],
];

export function groupShoppingItems(items) {
  const buckets = new Map([...GROUPS.map(([label]) => [label, []]), ['Прочее', []]]);
  for (const item of items) {
    const name = normalizeSearch(item.name);
    const group = GROUPS.find(([, pattern]) => pattern.test(name))?.[0] ?? 'Прочее';
    buckets.get(group).push(item);
  }
  return [...buckets].filter(([, entries]) => entries.length);
}
